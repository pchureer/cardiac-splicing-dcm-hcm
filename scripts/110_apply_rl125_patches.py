# never repointed, with the reason
PROTECTED = {
    "rmats_LBNL": "library-prep replicate, genuinely 50 bp",
    "rmats_Colorado": "independent cohort, own read length",
    "rmats_Brigham": "independent cohort, own read length",
    "rmats_Fuwai": "independent cohort, paired-end 150 bp",
    "rmats_Stanford": "independent cohort, own read length",
}

OUT_RE = r"(--out\s+)(\"?)({})(\"?)(?=\s|$)"


def noncomment_count(text, needle):
    return sum(ln.count(needle) for ln in text.splitlines()
               if not ln.lstrip().startswith("#"))


def patch_text(text, spec, problems):
    lines = text.splitlines(keepends=True)
    out_lines = []
    for ln in lines:
        if ln.lstrip().startswith("#"):
            out_lines.append(ln)
            continue
        new = ln
        for old, _n in spec["dirs"].items():
            new = new.replace(old, old[:-1] + SUFFIX + "/")
        for pref in spec["outs"]:
            pat = OUT_RE.format(re.escape(pref))
            new = re.sub(pat, lambda m: f"{m.group(1)}{m.group(2)}"
                                        f"{m.group(3)}{SUFFIX}{m.group(4)}", new)
        for tok in spec.get("tokens", {}):
            new = re.sub(re.escape(tok) + r"(?!" + SUFFIX + ")",
                         tok + SUFFIX, new)
        out_lines.append(new)
    return "".join(out_lines)


def do_one(path, spec, apply_, report):
    def w(s=""):
        report.append(s)

    w(f"═══ {path}")
    if not os.path.exists(path):
        w("    NOT FOUND -- skipped")
        w()
        return None
    text = open(path, errors="replace").read()

    # --- protected directories: report, never touch
    for d, why in PROTECTED.items():
        if noncomment_count(text, d + "/"):
            w(f"    protected: {d}/ present and LEFT ALONE ({why})")

    if not spec["dirs"] and not spec["outs"] and not spec.get("tokens"):
        w("    no mechanical edit for this script")
        for m in spec["manual"]:
            w(f"    MANUAL: {m}")
        w()
        return None

    # --- occurrence gate
    bad = False
    for old, want in spec["dirs"].items():
        got = noncomment_count(text, old)
        already = noncomment_count(text, old[:-1] + SUFFIX + "/")
        if got == 0 and already:
            w(f"    {old} already repointed ({already}x {old[:-1]}{SUFFIX}/)")
            continue
        if got != want:
            w(f"    ✗ expected {want}x '{old}' on non-comment lines, found {got}")
            bad = True
        else:
            w(f"    ✓ {got}x '{old}'  ->  '{old[:-1]}{SUFFIX}/'")
    for tok, want in spec.get("tokens", {}).items():
        got = noncomment_count(text, tok) - noncomment_count(text, tok + SUFFIX)
        already = noncomment_count(text, tok + SUFFIX)
        if got == 0 and already:
            w(f"    {tok} already suffixed ({already}x)")
            continue
        if got != want:
            w(f"    ✗ expected {want}x '{tok}' on non-comment lines, found {got}")
            bad = True
        else:
            w(f"    ✓ {got}x '{tok}'  ->  '{tok}{SUFFIX}'")
    for pref in spec["outs"]:
        n = len(re.findall(OUT_RE.format(re.escape(pref)), text))
        n_done = len(re.findall(OUT_RE.format(re.escape(pref + SUFFIX)), text))
        if n == 0 and n_done:
            w(f"    --out {pref} already renamed")
        elif n == 0:
            w(f"    ✗ --out {pref} not found")
            bad = True
        else:
            w(f"    ✓ --out {pref}  ->  {pref}{SUFFIX}  ({n}x)")
    if bad:
        w("    REFUSED: the file is not what the audit measured. Re-run "
          "108_rl125_rerun_audit.py and send me the new plan rather than "
          "forcing this.")
        for m in spec["manual"]:
            w(f"    MANUAL: {m}")
        w()
        return False

    new = patch_text(text, spec, report)
    if new == text:
        w("    nothing to change (already patched)")
        for m in spec["manual"]:
            w(f"    MANUAL: {m}")
        w()
        return None

    diff = list(difflib.unified_diff(
        text.splitlines(), new.splitlines(),
        fromfile=path + " (50 bp)", tofile=path + " (125 bp)", lineterm="", n=1))
    w("    --- diff ---")
    for d in diff:
        w(f"    {d}")

    if apply_:
        stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        bak = f"{path}.bak_{stamp}"
        shutil.copy2(path, bak)
        open(path, "w").write(new)
        chk = open(path, errors="replace").read()
        ok = True
        for old in spec["dirs"]:
            if noncomment_count(chk, old):
                w(f"    ✗ POST-CHECK FAILED: '{old}' still present")
                ok = False
        for pref in spec["outs"]:
            if re.search(OUT_RE.format(re.escape(pref)) + r"(?!%s)" % SUFFIX, chk):
                pass  # the rename appended, so the bare prefix no longer matches
        for tok in spec.get("tokens", {}):
            left = noncomment_count(chk, tok) - noncomment_count(chk, tok + SUFFIX)
            if left:
                w(f"    ✗ POST-CHECK FAILED: {left}x bare '{tok}' remains")
                ok = False
            if SUFFIX + SUFFIX in chk:
                w("    ✗ POST-CHECK FAILED: double suffix produced")
                ok = False
        for d, why in PROTECTED.items():
            if noncomment_count(text, d + "/") != noncomment_count(chk, d + "/"):
                w(f"    ✗ POST-CHECK FAILED: protected {d}/ was modified")
                ok = False
        w(f"    {'[ok] applied' if ok else '[FATAL] applied but post-check failed'}"
          f"; backup {bak}")
        if not ok:
            w(f"    restore with: cp {bak} {path}")
    else:
        w("    (dry run -- pass --apply to write)")

    for m in spec["manual"]:
        w(f"    MANUAL: {m}")
    w()
    return True


def self_test():
    import tempfile
    d = tempfile.mkdtemp()
    p = os.path.join(d, "36_matched_pair_panel.sbatch")
    open(p, "w").write(
        "#!/bin/bash\n"
        "# rmats_magnet in a comment must not be touched\n"
        "python x.py --mats rmats_magnet/${ET}.MATS.JCEC.txt --out mp_${ET}_selection \\\n"
        "    --b1 dcm_bams.txt --cov magnet_covariates.tsv\n"
        "python x.py --mats rmats_magnet/${ET}.MATS.JCEC.txt --out mp_${ET}_magnet_matched\n"
        "python x.py --mats rmats_LBNL/${ET}.MATS.JCEC.txt --out mp_${ET}_lbnl_matched\n"
        "python x.py --mats rmats_magnet/${ET}.MATS.JCEC.txt --out mp_${ET}_magnet_other\n")
    spec = PLAN["36_matched_pair_panel.sbatch"]
    rep = []
    r = do_one(p, spec, True, rep)
    txt = open(p).read()
    assert r is True, "\n".join(rep)
    assert txt.count("rmats_magnet_rl125/") == 3, txt
    assert "rmats_LBNL/" in txt and "rmats_LBNL_rl125" not in txt, "LBNL touched!"
    assert "# rmats_magnet in a comment" in txt, "comment was edited"
    assert "--out mp_${ET}_selection_rl125" in txt
    assert "--out mp_${ET}_lbnl_matched_rl125" in txt
    assert "--b1 dcm_bams.txt" in txt and "--cov magnet_covariates.tsv" in txt, \
        "metadata renamed!"
    # idempotency
    rep2 = []
    do_one(p, spec, True, rep2)
    assert open(p).read().count("rmats_magnet_rl125_rl125") == 0, "double-applied"
    # occurrence gate: a file with the wrong count must be refused
    p2 = os.path.join(d, "08_composition_adjusted_discovery.sbatch")
    open(p2, "w").write("python x.py --mats rmats_magnet/a --mats rmats_magnet/b "
                        "--out ${ET}_v2compadj\n")
    rep3 = []
    r3 = do_one(p2, PLAN["08_composition_adjusted_discovery.sbatch"], False, rep3)
    assert r3 is False, "\n".join(rep3)
    assert "REFUSED" in "\n".join(rep3)
    print("[ok] self-test passed: 3 MAGNet paths repointed, LBNL untouched, "
          "comments untouched, metadata untouched, 4 outputs renamed, "
          "idempotent, and the occurrence gate refuses a changed file")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scripts", nargs="*")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()

    rep = ["=" * 78,
           f"rl125 PATCH -- {'APPLYING' if a.apply else 'DRY RUN'}",
           "=" * 78, ""]
    order = a.scripts or list(PLAN)
    refused = []
    for s in order:
        if s not in PLAN:
            rep.append(f"═══ {s}\n    no plan entry; run 108 on it first\n")
            continue
        if do_one(s, PLAN[s], a.apply, rep) is False:
            refused.append(s)

    rep += ["=" * 78, "SUBMISSION ORDER -- dependencies, not preference", "=" * 78,
            "1. 08  compadj / fulladj      -> gives 899 and 835, AND the compadj",
            "                                  tables the 134-gene list and the",
            "                                  927-gene foreground derive from",
            "2. 04  legacy / pooladj / age25 -> gives 866 and 888",
            "3. 72 + 75  cmfrac            -> gives 1,054 / 716 / 590",
            "4. rebuild the foreground and the 134-gene list (93, 13)",
            "5. 23  inverted RBP scan      -> MUST come after step 4",
            "6. 56  forward 45-gene test",
            "7. 36  matched-pair panel     -> independent, can go first",
            "8. 20  JC vs JCEC             -> independent, can go first",
            "9. 21  replication            -> no quantification re-run; the",
            "                                  selection step needs manual review",
            "",
            "1 CPU each (phase2 is a serial iterrows loop). 36 and 20 can run",
            "alongside 08 within 96 GB. Do NOT edit a gate constant yet."]
    if refused:
        rep += ["", "=" * 78,
                f"✗ REFUSED {len(refused)} script(s): {refused}",
                "NOTHING WAS WRITTEN for those. Exiting non-zero so that",
                "`110 --apply && sbatch ...` stops here instead of submitting an",
                "unpatched script against 50 bp data.",
                "=" * 78]
    print("\n".join(rep))
    return 1 if refused else 0


if __name__ == "__main__":
    sys.exit(main())
